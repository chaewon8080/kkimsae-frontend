// 선택지 형식:
// [
//   버튼 문구,
//   다음 장면 ID,
//   복기에 표시할 행동,
//   행동 해설,
//   내 말풍선으로 표시할 대사(선택)
// ]

function choice(
  label,
  next,
  action,
  feedback,
  reply
) {
  return [
    label,
    next,
    action,
    feedback,
    reply,
  ];
}

function confirmChoice() {
  return choice(
    '통화를 끊고 공식 경로로 확인한다',
    'verified',
    '안내를 중단하고 별도 경로로 확인하기로 했습니다.',
    '상대가 보낸 링크와 연락처를 그대로 이용하지 않고, 독립적인 확인 경로를 선택했습니다.'
  );
}

